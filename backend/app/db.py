"""Accesso al database: SQLite in locale, Postgres (Supabase) online.

Il codice scrive SQL con i segnaposto `?`. Con Postgres li traduciamo in `%s`.
DATABASE_URL:
  sqlite:///percorso/app.db       (predefinito, in DATA_DIR)
  postgresql://utente:pw@host:6543/postgres   (Supabase, pooler)
DB_SCHEMA: schema Postgres da usare (utile per stare dentro un progetto Supabase esistente).
"""
import json
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path

from . import config

HERE = Path(__file__).parent


class Conn:
    """Involucro minimo con la stessa interfaccia per i due motori."""

    def __init__(self, raw, pg: bool):
        self.raw, self.pg = raw, pg

    def _sql(self, sql: str, params) -> str:
        if not self.pg:
            return sql
        if params is not None:
            sql = sql.replace("%", "%%")
        return sql.replace("?", "%s")

    def execute(self, sql: str, params=None):
        if self.pg:
            cur = self.raw.cursor()
            cur.execute(self._sql(sql, params), params)
            return cur
        return self.raw.execute(sql, params or ())

    def insert(self, sql: str, params=()) -> int:
        """INSERT che restituisce l'id della nuova riga."""
        if self.pg:
            return self.execute(sql + " RETURNING id", params).fetchone()["id"]
        return self.raw.execute(sql, params).lastrowid

    def executescript(self, script: str) -> None:
        if self.pg:
            self.raw.execute(script)
        else:
            self.raw.executescript(script)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def _is_pg(url: str) -> bool:
    return url.startswith("postgres")


def connect(url: str | Path | None = None) -> Conn:
    url = str(url or config.DATABASE_URL)
    if _is_pg(url):
        import psycopg
        from psycopg.rows import dict_row

        # prepare_threshold=None: il pooler di Supabase non regge i prepared statement
        raw = psycopg.connect(url, row_factory=dict_row, prepare_threshold=None)
        raw.execute(f'SET search_path TO "{config.DB_SCHEMA}"')
        return Conn(raw, True)
    path = url.removeprefix("sqlite:///")
    raw = sqlite3.connect(path, check_same_thread=False)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    raw.execute("PRAGMA journal_mode = WAL")
    return Conn(raw, False)


def to_postgres(script: str) -> str:
    """Traduce lo schema SQLite in Postgres."""
    script = re.sub(r"PRAGMA[^;]*;", "", script)
    script = script.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    script = script.replace("(datetime('now'))", "(to_char(now(), 'YYYY-MM-DD HH24:MI:SS'))")
    return script


def _tables_with_id(conn: Conn) -> list[str]:
    return [r["table_name"] for r in conn.execute(
        "SELECT table_name FROM information_schema.columns WHERE table_schema = ? AND column_name = 'id' "
        "AND is_identity = 'YES'", (config.DB_SCHEMA,))]


def init_db(url: str | Path | None = None) -> None:
    """Crea le tabelle e carica i dati iniziali, solo se il database è nuovo."""
    url = str(url or config.DATABASE_URL)
    if _is_pg(url):
        import psycopg
        with psycopg.connect(url, autocommit=True) as raw:
            raw.execute(f'CREATE SCHEMA IF NOT EXISTS "{config.DB_SCHEMA}"')
    conn = connect(url)
    try:
        if conn.pg:
            exists = conn.execute(
                "SELECT 1 FROM information_schema.tables WHERE table_schema = ? AND table_name = 'settings'",
                (config.DB_SCHEMA,)).fetchone()
        else:
            exists = conn.execute(
                "SELECT 1 FROM sqlite_master WHERE type='table' AND name='settings'").fetchone()
        if not exists:
            schema = (HERE / "schema.sql").read_text()
            seed = (HERE / "seed.sql").read_text()
            if conn.pg:
                conn.executescript(to_postgres(schema))
                conn.executescript(seed)
                for t in _tables_with_id(conn):
                    conn.execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), "
                                 f"COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")
            else:
                conn.executescript(schema)
                conn.executescript(seed)
            conn.commit()
        _migrate(conn)
        conn.commit()
    finally:
        conn.close()


# Colonne aggiunte dopo la prima versione: (tabella, colonna, definizione).
MIGRATIONS = [("garments", "to_review", "INTEGER NOT NULL DEFAULT 0")]


def _migrate(conn) -> None:
    """Aggiunge le colonne nuove ai database già creati, senza toccare i dati."""
    for table, col, ddl in MIGRATIONS:
        if conn.pg:
            conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {col} {ddl}")
        else:
            cols = {r["name"] for r in conn.execute(f"PRAGMA table_info({table})").fetchall()}
            if col not in cols:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {col} {ddl}")


@contextmanager
def session(url: str | Path | None = None):
    conn = connect(url)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def get_db():
    """Dipendenza FastAPI: una connessione per richiesta."""
    with session() as conn:
        yield conn


def rows(cur) -> list[dict]:
    return [dict(r) for r in cur.fetchall()]


def row(cur) -> dict | None:
    r = cur.fetchone()
    return dict(r) if r else None


def get_setting(conn, key: str, default=None):
    r = conn.execute("SELECT value FROM settings WHERE key = ?", (key,)).fetchone()
    return json.loads(r["value"]) if r else default


def set_setting(conn, key: str, value) -> None:
    conn.execute(
        "INSERT INTO settings(key, value) VALUES (?, ?) "
        "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
        (key, json.dumps(value)),
    )
